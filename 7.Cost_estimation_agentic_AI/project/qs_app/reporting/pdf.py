# ----------------------------- helpers -----------------------------

def _symbol(currency: str) -> str:
    return {"AUD": "A$", "USD": "$", "INR": "Rs", "EUR": "€", "GBP": "£"}.get(str(currency).upper(), currency + " ")

def fmt_money(v, currency="AUD") -> str:
    try:
        n = float(v)
    except Exception:
        return "—"
    return f"{_symbol(currency)}{n:,.0f}"

def _pct(v) -> str:
    try:
        return f"{float(v)*100:.1f}%"
    except Exception:
        return "—"

def safe(val, default="—"):
    return default if val in (None, "", "N/A") else val


# ----------------------------- footer canvas -----------------------------

class FooterCanvas(canvas.Canvas):
    """
    Custom canvas so we can draw page numbers & timestamp on every page.
    Usage: doc.build(story, canvasmaker=FooterCanvas)
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_pages = []

    def showPage(self):
        self._saved_pages.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        for page in self._saved_pages:
            self.__dict__.update(page)
            self._draw_footer()
            super().showPage()
        super().save()

    def _draw_footer(self):
        w, h = A4
        ts = datetime.now().strftime("%d %b %Y, %I:%M %p")
        left = "Generated by QS Agentic AI"
        mid = ts
        right = f"Page {self._pageNumber}"

        self.setFont("Helvetica", 9)
        self.setFillColor(colors.grey)

        self.drawString(20 * mm, 12 * mm, left)
        midw = stringWidth(mid, "Helvetica", 9)
        self.drawString((w - midw) / 2, 12 * mm, mid)
        rw = stringWidth(right, "Helvetica", 9)
        self.drawString(w - 20 * mm - rw, 12 * mm, right)

        self.setFillColor(colors.black)


# ----------------------------- tiny horizontal rule -----------------------------

class HR(Flowable):
    def __init__(self, width=170 * mm, thickness=0.6, color=colors.HexColor("#DDDDDD")):
        super().__init__()
        self.width = width
        self.thickness = thickness
        self.color = color
        self.height = thickness

    def draw(self):
        self.canv.setStrokeColor(self.color)
        self.canv.setLineWidth(self.thickness)
        self.canv.line(0, 0, self.width, 0)


# ----------------------------- main: build_cost_report -----------------------------

def build_cost_report(
    data: Dict[str, Any],
    meta: Dict[str, Any],
    citations: Optional[List[Dict[str, Any]]] = None,
) -> bytes:
    """
    data (normalized):
      {
        "parsed": {...},
        "estimate": {"factors": {...}, "breakdown": {...}},
        "assumptions": {...},
        "question": str?
      }

    meta:
      {
        "company_name": str,
        "client_name": str,
        "project_name": str,
        "logo_path": str?,         # local path; optional
        "currency": "AUD"|"INR"|...,
        "api_link": str?,          # for QR
        "notes": str?              # extra line under header
      }

    citations (optional):
      [{ "source": "location_factors.csv", "row": 12, "snippet": "..." }, ...]
    """
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=20 * mm,
        rightMargin=20 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="QS Agentic AI – Cost Report",
        author=safe(meta.get("company_name"), "QS Agentic AI"),
    )

    styles = getSampleStyleSheet()
    title = ParagraphStyle("title", parent=styles["Heading1"], fontSize=18, leading=22, spaceAfter=6)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=13, leading=16, spaceBefore=10, spaceAfter=6)
    body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=10.5, leading=14)

    story: List[Any] = []

    # ---------- Header (logo + meta) ----------
    logo_path = meta.get("logo_path")
    left_cells: List[Any] = [
        Paragraph(f"<b>{safe(meta.get('company_name'), 'Company')}</b>", title),
        Paragraph(
            f"<b>Project:</b> {safe(meta.get('project_name'))}<br/>"
            f"<b>Client:</b> {safe(meta.get('client_name'))}", body
        ),
    ]
    if meta.get("notes"):
        left_cells.append(Paragraph(safe(meta.get("notes")), body))

    img = Paragraph("", body)
    if logo_path and isinstance(logo_path, str) and os.path.isfile(logo_path):
        try:
            ImageReader(logo_path)  # validate readability
            img = Image(logo_path, width=37 * mm, height=16 * mm, hAlign="RIGHT")
        except Exception:
            img = Paragraph("", body)

    header_tbl = Table([[left_cells, img]], colWidths=[130 * mm, 40 * mm])
    header_tbl.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN", (1, 0), (1, 0), "RIGHT")
    ]))
    story += [header_tbl, Spacer(1, 4 * mm), HR(), Spacer(1, 6 * mm)]

    # ---------- Summary ----------
    q = data.get("question")
    parsed = data.get("parsed", {}) or {}
    est = data.get("estimate", {}) or {}
    factors = est.get("factors", {}) or {}
    br = est.get("breakdown", {}) or {}
    currency = meta.get("currency", "AUD")

    if q:
        story.append(Paragraph(f"<b>Question:</b> {q}", body))
        story.append(Spacer(1, 2 * mm))

    top_summary = (
        f"For a <b>{safe(parsed.get('gfa_m2'))}</b> m² project in "
        f"<b>{safe(parsed.get('city'))}</b> targeted for <b>{safe(parsed.get('need_year'))}</b> "
        f"at <b>{safe(parsed.get('stage'))}</b> stage with <b>{safe(parsed.get('sustainability'))}</b>."
    )
    story.append(Paragraph(top_summary, body))
    story.append(Paragraph(
        f"<font size=13><b>Estimated Total:</b> {fmt_money(br.get('final_with_contingency'), currency)}</font>",
        h2
    ))
    story.append(Paragraph(f"<i>All costs shown in {currency}.</i>", body))
    story.append(Spacer(1, 4 * mm))

    # ---------- Breakdown table ----------
    tbl_data = [
        ["Step", "Value"],
        ["Base cost", fmt_money(br.get("base_cost"), currency)],
        [f"After location (× {safe(factors.get('location_factor'))})", fmt_money(br.get("after_location"), currency)],
        [f"After escalation (× {safe(factors.get('escalation_factor'))})", fmt_money(br.get("after_escalation"), currency)],
        [f"Sustainability uplift (+ {_pct(factors.get('sustainability_uplift_pct'))})", fmt_money(br.get("after_sustainability"), currency)],
        [f"Contingency (+ {_pct(factors.get('contingency_pct'))})", fmt_money(br.get("final_with_contingency"), currency)],
    ]
    tbl = Table(tbl_data, colWidths=[110 * mm, 60 * mm])
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F3F3F3")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.black),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("ALIGN", (1, 1), (1, -1), "RIGHT"),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#DDDDDD")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#FAFAFA")]),
    ]))
    story += [tbl, Spacer(1, 8 * mm)]

    # ---------- Mini bar chart ----------
    vals = [
        br.get("base_cost"),
        br.get("after_location"),
        br.get("after_escalation"),
        br.get("after_sustainability"),
        br.get("final_with_contingency"),
    ]
    labels = ["Base", "Loc", "Esc", "Sus", "Final"]
    drawing = Drawing(160 * mm, 60 * mm)
    chart = VerticalBarChart()
    chart.x = 20
    chart.y = 15
    chart.width = 130 * mm
    chart.height = 40 * mm
    chart.data = [[float(v) if isinstance(v, (int, float)) else 0.0 for v in vals]]
    chart.categoryAxis.categoryNames = labels
    chart.categoryAxis.labels.fontName = "Helvetica"
    chart.valueAxis.labels.fontName = "Helvetica"
    chart.valueAxis.visibleGrid = True
    chart.valueAxis.gridStrokeColor = colors.HexColor("#E6E6E6")
    chart.strokeColor = colors.HexColor("#666666")
    drawing.add(chart)
    drawing.add(String(20, 58 * mm, "Cost Progression", fontName="Helvetica-Bold", fontSize=10))
    story += [drawing, Spacer(1, 8 * mm)]

    # ---------- Optional QR (api_link) ----------
    api_link = meta.get("api_link")
    if api_link:
        d = Drawing(40 * mm, 40 * mm)
        w = qr.QrCodeWidget(api_link)
        w.barWidth = 35 * mm
        w.barHeight = 35 * mm
        d.add(w)
        story += [Paragraph("<b>Run link (QR):</b>", body), d, Spacer(1, 6 * mm)]

    # ---------- Assumptions ----------
    story += [Paragraph("Assumptions & Notes", h2), HR()]
    assumptions = data.get("assumptions", {})
    if isinstance(assumptions, dict):
        formula = assumptions.get("formula")
        if formula:
            story.append(Paragraph(f"<b>Formula:</b> {formula}", body))
        notes = assumptions.get("notes") or []
        if notes:
            for n in notes:
                story.append(Paragraph(f"• {n}", body))
    else:
        story.append(Paragraph("—", body))
    story.append(Spacer(1, 4 * mm))

    # ---------- Citations ----------
    story += [Paragraph("Sources & Citations", h2), HR()]
    if citations:
        # show max ~10 to keep page tidy
        shown = citations[:10]
        for h in shown:
            tag = f"[{h.get('source')} R{h.get('row')}]"
            story.append(Paragraph(f"• {tag}: {h.get('snippet')}", body))
        if len(citations) > len(shown):
            story.append(Paragraph(f"… and {len(citations) - len(shown)} more.", body))
    else:
        story.append(Paragraph("—", body))

    # build
    doc.build(story, canvasmaker=FooterCanvas)
    buf.seek(0)
    return buf.getvalue()
